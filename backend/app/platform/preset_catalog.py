FALLBACK = DEMO_CATALOG["other"]


def seed_preset_catalog(db: Session, tenant_id: int, preset: str | None) -> int:
    rows = DEMO_CATALOG.get(preset or "") or FALLBACK
    created = 0
    for order, (slug, title, description, products) in enumerate(rows):
        if db.scalar(
            select(Category.id).where(
                Category.tenant_id == tenant_id, Category.slug == slug
            )
        ):
            continue
        category = Category(
            tenant_id=tenant_id,
            slug=slug,
            title=title,
            description=description,
            sort_order=(order + 1) * 10,
            is_active=True,
        )
        db.add(category)
        db.flush()
        for index, (product_slug, product_title, price, unit, short) in enumerate(products):
            if db.scalar(
                select(Product.id).where(
                    Product.tenant_id == tenant_id, Product.slug == product_slug
                )
            ):
                continue
            db.add(
                Product(
                    tenant_id=tenant_id,
                    slug=product_slug,
                    title=product_title,
                    subtitle="",
                    category_id=category.id,
                    unit=unit,
                    price=money(Decimal(str(price))),
                    discount_percent=0,
                    is_daily_deal=False,
                    is_available=True,
                    is_active=True,
                    stock=None,
                    weight_note="",
                    image_url=None,
                    gallery=[],
                    badges=[],
                    short_description=short,
                    description=short,
                    origin="",
                    season="",
                    nutrition={},
                    cooking_tips="",
                    storage_tips="",
                    sort_order=(index + 1) * 10,
                )
            )
            created += 1
    db.commit()
    return created
